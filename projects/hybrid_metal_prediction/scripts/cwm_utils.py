"""Community-weighted mean (CWM) per-Mb density computation.

For each sample, CWM_category = Σ_genus (RA_genus × density_genus_category).

Usage
-----
from cwm_utils import load_otu_bridge, load_genus_densities, compute_cwm
from cwm_utils import load_genus_ra_from_spark

bridge = load_otu_bridge()
densities = load_genus_densities()

# From Spark (JupyterHub)
ra_pivot = load_genus_ra_from_spark(spark, sample_ids=my_ids, otu_bridge=bridge)
cwm_df = compute_cwm(ra_pivot, densities)
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Optional, List

import numpy as np
import pandas as pd

log = logging.getLogger(__name__)

DATA_DIR = Path(__file__).parent.parent / "data"

COVERAGE_FLAG_THRESHOLD = 0.70  # flag samples with <70% RA covered

# Columns in genus_trait_table.csv used as CWM features
# (verified against comprehensive_metal_ecology/data/genus_trait_table.csv)
DENSITY_COLS = [
    "mean_n_metal_clusters",       # total metal gene clusters (all categories)
    "mean_n_defense_clusters",     # resistance/defense gene clusters
    "mean_n_metabolism_clusters",  # primary metabolism clusters (cofactor)
    "mean_n_homeostasis_clusters", # homeostasis/transport/sensing clusters
    "mean_metal_core_fraction",    # fraction of genome that is metal core
]


# ---------------------------------------------------------------------------
# OTU bridge
# ---------------------------------------------------------------------------

def load_otu_bridge(path: Optional[Path] = None) -> pd.DataFrame:
    """Load OTU-to-genus mapping.

    Returns DataFrame with columns: otu_id, genus_lower.
    """
    p = path or DATA_DIR / "otu_pangenome_link_v2.csv"
    raw = pd.read_csv(p)
    raw.columns = raw.columns.str.lower().str.strip()

    # Accept various column name conventions
    alias_id = {"otu_id", "otuid", "#otu id", "otu"}
    alias_genus = {"genus_lower", "genus", "genus_name"}

    id_col = next((c for c in raw.columns if c in alias_id), None)
    genus_col = next((c for c in raw.columns if c in alias_genus), None)

    if id_col is None or genus_col is None:
        raise ValueError(
            f"Could not find otu_id / genus_lower columns in {p}. "
            f"Found: {list(raw.columns)}"
        )

    out = raw[[id_col, genus_col]].rename(
        columns={id_col: "otu_id", genus_col: "genus_lower"}
    )
    out["genus_lower"] = out["genus_lower"].str.lower().str.strip()
    return out.dropna().drop_duplicates("otu_id")


# ---------------------------------------------------------------------------
# Density loading
# ---------------------------------------------------------------------------

def load_genus_densities(
    genus_trait_path: Optional[Path] = None,
    landscape_density_path: Optional[Path] = None,
) -> pd.DataFrame:
    """Load per-genus per-Mb density table.

    Primary source: genus_trait_table.csv (metal functional categories).
    Optional: genus_functional_landscape_densities.csv (19 KEGG categories,
              generated by running the Spark density query from NB00 of this project).

    Returns DataFrame indexed by genus_lower with density columns.
    """
    trait_path = genus_trait_path or DATA_DIR / "genus_trait_table.csv"

    wanted_cols = {"genus_lower"} | set(DENSITY_COLS)
    avail = set(pd.read_csv(trait_path, nrows=0).columns)
    use_cols = list(wanted_cols & avail)

    trait = pd.read_csv(trait_path, usecols=use_cols)
    trait["genus_lower"] = trait["genus_lower"].str.lower().str.strip()
    trait = trait.drop_duplicates("genus_lower").set_index("genus_lower")

    # Optionally join landscape densities
    land_path = landscape_density_path or DATA_DIR / "genus_functional_landscape_densities.csv"
    if land_path.exists():
        land = pd.read_csv(land_path)
        land["genus_lower"] = land["genus_lower"].str.lower().str.strip()
        land = land.drop_duplicates("genus_lower").set_index("genus_lower")
        trait = trait.join(land, how="outer")

    return trait


# ---------------------------------------------------------------------------
# CWM computation
# ---------------------------------------------------------------------------

def compute_cwm(
    sample_genus_ra: pd.DataFrame,
    genus_densities: pd.DataFrame,
    coverage_threshold: float = COVERAGE_FLAG_THRESHOLD,
) -> pd.DataFrame:
    """Compute community-weighted mean densities per sample.

    Parameters
    ----------
    sample_genus_ra : DataFrame
        shape (n_samples, n_genera); values are relative abundances (row-sums ≈ 1).
        Index = sample_id; columns = genus_lower.
    genus_densities : DataFrame
        shape (n_genera, n_categories); index = genus_lower.
    coverage_threshold : float
        Flag samples where matched RA fraction < threshold.

    Returns
    -------
    DataFrame indexed by sample_id with columns:
        CWM_{category} for each category in genus_densities,
        coverage_fraction, low_coverage_flag.
    """
    common = sample_genus_ra.columns.intersection(genus_densities.index)

    if len(common) == 0:
        raise ValueError(
            "No genera overlap between OTU table and density table. "
            "Check that genus names are lowercase-normalised in both inputs."
        )

    matched_ra = sample_genus_ra[common]
    matched_den = genus_densities.loc[common].fillna(0.0)

    total_ra = sample_genus_ra.sum(axis=1).replace(0.0, np.nan)
    coverage = matched_ra.sum(axis=1) / total_ra

    # Matrix multiply: (n_samples × n_matched) @ (n_matched × n_cats) = (n_samples × n_cats)
    cwm_vals = matched_ra.values @ matched_den.values
    cwm_df = pd.DataFrame(
        cwm_vals,
        index=sample_genus_ra.index,
        columns=[f"CWM_{c}" for c in matched_den.columns],
    )
    cwm_df["coverage_fraction"] = coverage.values
    cwm_df["low_coverage_flag"] = coverage.values < coverage_threshold

    n_flagged = cwm_df["low_coverage_flag"].sum()
    if n_flagged > 0:
        log.warning(
            "%d / %d samples have coverage < %.0f%%.",
            n_flagged, len(cwm_df), coverage_threshold * 100,
        )

    return cwm_df


# ---------------------------------------------------------------------------
# Spark data retrieval
# ---------------------------------------------------------------------------

def load_genus_ra_from_spark(
    spark,
    sample_ids: Optional[list] = None,
    otu_bridge: Optional[pd.DataFrame] = None,
    min_ra: float = 1e-5,
    otu_col: str = "otu_id",
) -> pd.DataFrame:
    """Pull OTU counts from Spark and aggregate to genus relative abundances.

    Returns wide DataFrame: index=sample_id, columns=genus_lower, values=RA.
    """
    if otu_bridge is None:
        otu_bridge = load_otu_bridge()

    otu_ids = otu_bridge["otu_id"].astype(str).tolist()
    otu_str = "', '".join(otu_ids)

    sid_clause = ""
    if sample_ids is not None:
        sid_str = "', '".join(str(s) for s in sample_ids)
        sid_clause = f"AND oc.sample_id IN ('{sid_str}')"

    sql = f"""
        SELECT oc.sample_id, oc.{otu_col} AS otu_id, oc.count
        FROM arkinlab.microbeatlas.otu_counts_long oc
        WHERE oc.{otu_col} IN ('{otu_str}')
        {sid_clause}
    """
    counts = spark.sql(sql).toPandas()
    counts.attrs.clear()

    if counts.empty:
        raise ValueError("No OTU counts returned from Spark. Check sample_ids and otu_col.")

    counts = counts.merge(otu_bridge, on="otu_id", how="left").dropna(subset=["genus_lower"])

    genus_counts = (
        counts.groupby(["sample_id", "genus_lower"])["count"]
        .sum()
        .reset_index()
    )

    total = genus_counts.groupby("sample_id")["count"].transform("sum")
    genus_counts["ra"] = genus_counts["count"] / total.replace(0, np.nan)
    genus_counts = genus_counts[genus_counts["ra"] >= min_ra]

    pivot = genus_counts.pivot_table(
        index="sample_id", columns="genus_lower", values="ra", fill_value=0.0
    )
    log.info(
        "Loaded RA for %d samples × %d genera (min RA ≥ %.1e).",
        pivot.shape[0], pivot.shape[1], min_ra,
    )
    return pivot


# ---------------------------------------------------------------------------
# Utility
# ---------------------------------------------------------------------------

def summarise_cwm(cwm_df: pd.DataFrame) -> pd.DataFrame:
    """Return summary statistics for the CWM feature matrix."""
    cols = [c for c in cwm_df.columns if c.startswith("CWM_")]
    return cwm_df[cols].describe().T.round(4)
